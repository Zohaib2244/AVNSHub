// Widget Creator verify step (docs/design/WIDGET_SIZE_PRESETS.md §10). After a build
// is applied, the widget is rendered alone at each declared preset's min, max
// and readability floor (and three region shapes for hero) through
// /dev/widget-frame, and anything that doesn't fit is reported.
//
// How it reaches a widget that isn't registered yet: app/dev/widget-frame/
// target.ts is pointed at the widget's component with a static import, only
// for the duration of the check, then the stub is written back. Only the dev
// frame page imports that file, so the dashboard never recompiles or reloads.
//
// The browser runs in its own process (scripts/verify-widget-frame.mjs), and
// Playwright is found at runtime rather than being a project dependency; with
// none installed the step is skipped, never failed.

import { spawn } from "child_process";
import { existsSync, mkdtempSync, rmSync, writeFileSync } from "fs";
import { homedir, tmpdir } from "os";
import { join } from "path";
import { SIZE_PRESETS, type PresetId } from "@/config/sizePresets";
import { DEFAULT_FRAME_RATIOS } from "@/config/slotLayout";
import { REFERENCE_FRAME, regionBoxes, standardCell } from "@/lib/grid/standardCell";
import { prisma } from "@/lib/db";
import { findComponentModule, type RegistryEntry } from "./customRegistry";

const ROOT = process.cwd();
const TARGET_PATH = join(ROOT, "app/dev/widget-frame/target.ts");
const PROBE_PATH = join(ROOT, "scripts/verify-widget-frame.mjs");
const PROBE_TIMEOUT_MS = 5 * 60_000;

/** app/dev/widget-frame/target.ts as committed — restored after every check */
export const TARGET_STUB = `// Widget under test for /dev/widget-frame. The Widget Creator's verify step
// (lib/widget-creator/verifyWidget.ts) points this at the widget it is
// checking, then writes this stub back. Keep it a stub in git.
import type { VerifyTarget } from "./types";

export const VERIFY_TARGET: VerifyTarget | null = null;
`;

export type VerifyShot = { label: string; preset: PresetId; w: number; h: number };
export type VerifyShotResult = VerifyShot & { problems: string[]; screenshot?: string };
export type VerifyResult =
  | { status: "skipped"; reason: string }
  | { status: "passed" | "failed"; shots: VerifyShotResult[] };

/** A Playwright install to drive: $AVNHUB_PLAYWRIGHT, then a user-level
    playwright-kit, then one in the project's node_modules. */
export function findPlaywright(): string | null {
  const candidates = [
    process.env.AVNHUB_PLAYWRIGHT,
    join(homedir(), ".local/share/playwright-kit/node_modules/playwright/index.mjs"),
    join(ROOT, "node_modules/playwright/index.mjs"),
  ].filter((p): p is string => Boolean(p));
  return candidates.find((p) => existsSync(p)) ?? null;
}

/** the boxes to render, at the 1920×1080 reference frame */
export function verifyShots(presets: PresetId[]): VerifyShot[] {
  const sc = standardCell(REFERENCE_FRAME);
  const px = (cols: number, rows: number) => ({
    w: Math.round(cols * sc.pitchX - REFERENCE_FRAME.gap),
    h: Math.round(rows * sc.pitchY - REFERENCE_FRAME.gap),
  });
  const shots: VerifyShot[] = [];
  for (const id of presets) {
    const preset = SIZE_PRESETS[id];
    if (id === "hero") {
      const boxes = regionBoxes(REFERENCE_FRAME, DEFAULT_FRAME_RATIOS);
      for (const [label, box] of [["column", boxes.left], ["center", boxes.center], ["base", boxes.base]] as const) {
        shots.push({ label: `hero-${label}`, preset: id, w: Math.round(box.width), h: Math.round(box.height) });
      }
      continue;
    }
    if (preset.min) shots.push({ label: `${id}-min`, preset: id, ...px(preset.min.cols, preset.min.rows) });
    if (preset.max) shots.push({ label: `${id}-max`, preset: id, ...px(preset.max.cols, preset.max.rows) });
    if (preset.floorPx) shots.push({ label: `${id}-floor`, preset: id, w: preset.floorPx.width, h: preset.floorPx.height });
  }
  return shots;
}

function targetSource(slug: string, entry: RegistryEntry): string | null {
  const mod = findComponentModule(slug);
  if (!mod) return null;
  const from = `@/components/widgets/custom/${slug}/${mod.file}`;
  const importLine = mod.exportName
    ? `import { ${mod.exportName} as Target } from "${from}";`
    : `import Target from "${from}";`;
  const data = {
    title: entry.title,
    sizes: entry.sizes,
    orientations: entry.orientations,
    defaults: entry.defaults,
    minPx: entry.minPx,
    presets: entry.presets,
    defaultPreset: entry.defaultPreset,
    fill: entry.fill,
    settings: entry.settings ?? [],
    flags: entry.flags,
  };
  return `// GENERATED by the Widget Creator's verify step — restored to a stub when it finishes.
import type { VerifyTarget } from "./types";
${importLine}

export const VERIFY_TARGET: VerifyTarget | null = {
  id: ${JSON.stringify(slug)},
  entry: ${JSON.stringify(data)} as VerifyTarget["entry"],
  Component: Target,
};
`;
}

function runProbe(job: object, signal: AbortSignal): Promise<{ results: VerifyShotResult[] }> {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [PROBE_PATH], { cwd: ROOT, stdio: ["pipe", "pipe", "pipe"] });
    let out = "";
    let err = "";
    const timer = setTimeout(() => child.kill("SIGKILL"), PROBE_TIMEOUT_MS);
    const onAbort = () => child.kill("SIGKILL");
    signal.addEventListener("abort", onAbort, { once: true });
    child.stdout.on("data", (d: Buffer) => { out += d.toString(); });
    child.stderr.on("data", (d: Buffer) => { err += d.toString(); });
    child.on("error", reject);
    child.on("close", (code) => {
      clearTimeout(timer);
      signal.removeEventListener("abort", onAbort);
      if (code !== 0) return reject(new Error(err.trim().split("\n").slice(-3).join(" ") || `exited with code ${code}`));
      try { resolve(JSON.parse(out)); } catch { reject(new Error("the verify probe returned no result")); }
    });
    child.stdin.end(JSON.stringify(job));
  });
}

/** Render a just-applied widget at every declared preset and report what
    doesn't fit. Screenshots land in `outDir`, which the caller owns. */
export async function verifyWidget(opts: {
  slug: string;
  entry: RegistryEntry;
  baseUrl: string;
  outDir: string;
  signal: AbortSignal;
}): Promise<VerifyResult> {
  const presets = opts.entry.presets ?? [];
  if (!presets.length) return { status: "skipped", reason: "the widget declares no size presets" };
  const playwright = findPlaywright();
  if (!playwright) {
    return { status: "skipped", reason: "no Playwright install was found (set AVNHUB_PLAYWRIGHT to a playwright/index.mjs)" };
  }
  const source = targetSource(opts.slug, opts.entry);
  if (!source) return { status: "skipped", reason: "no component file to render" };

  writeFileSync(TARGET_PATH, source);
  try {
    const { results } = await runProbe(
      { playwright, baseUrl: opts.baseUrl, slug: opts.slug, outDir: opts.outDir, shots: verifyShots(presets) },
      opts.signal,
    );
    return { status: results.some((r) => r.problems.length) ? "failed" : "passed", shots: results };
  } catch (error) {
    if (opts.signal.aborted) throw error;
    return { status: "skipped", reason: `the headless check couldn't run: ${error instanceof Error ? error.message : String(error)}` };
  } finally {
    writeFileSync(TARGET_PATH, TARGET_STUB);
  }
}

export function makeShotsDir(): string {
  return mkdtempSync(join(tmpdir(), "avnhub-verify-"));
}

export function removeShotsDir(dir: string | null) {
  if (dir) rmSync(dir, { recursive: true, force: true });
}

/** one line per failing box, for prompts, notices and the warning flag */
export function describeFailures(result: VerifyResult): string[] {
  if (result.status !== "failed") return [];
  return result.shots
    .filter((s) => s.problems.length)
    .map((s) => `${s.label} (${s.w}×${s.h}px): ${s.problems.slice(0, 4).join("; ")}${s.problems.length > 4 ? `; and ${s.problems.length - 4} more` : ""}`);
}

// The outcome is kept per widget so "add to layout" — a separate request,
// possibly much later — can flag a widget that was installed with problems.
const kvKey = (slug: string) => `nutbot-verify:${slug}`;

export async function saveVerifyOutcome(slug: string, warning: string | null): Promise<void> {
  try {
    if (warning) {
      await prisma.kV.upsert({ where: { key: kvKey(slug) }, create: { key: kvKey(slug), value: JSON.stringify({ warning }) }, update: { value: JSON.stringify({ warning }) } });
    } else {
      await prisma.kV.deleteMany({ where: { key: kvKey(slug) } });
    }
  } catch (error) {
    console.error("Could not persist the widget verify outcome", error);
  }
}

export async function readVerifyWarning(slug: string): Promise<string | null> {
  try {
    const row = await prisma.kV.findUnique({ where: { key: kvKey(slug) } });
    const warning = row ? (JSON.parse(row.value) as { warning?: unknown }).warning : null;
    return typeof warning === "string" ? warning : null;
  } catch {
    return null;
  }
}
